# 1. Download GIFs locally
saved_guides = {}
headers = {'User-Agent': 'Mozilla/5.0'}

for name, item in EXERCISES_DATA.items():
    slug = item["slug"]
    local_filename = f"{slug}.gif"
    local_path = os.path.join(VIDEOS_DIR, local_filename)
    remote_url = BASE_RAW + item["remote_gif"]
    
    if not os.path.exists(local_path) or os.path.getsize(local_path) == 0:
        try:
            print(f"Downloading {local_filename} from {remote_url}...")
            req = urllib.request.Request(remote_url, headers=headers)
            with urllib.request.urlopen(req, timeout=15) as resp, open(local_path, "wb") as f:
                f.write(resp.read())
            print(f"  [OK] Saved {local_filename} ({os.path.getsize(local_path)} bytes)")
        except Exception as e:
            print(f"  [FAIL] Error downloading {name}: {e}")
            local_filename = None
    else:
        print(f"  [EXISTS] {local_filename} ({os.path.getsize(local_path)} bytes)")

    saved_guides[name] = {
        "name": name,
        "slug": slug,
        "local_video": f"/static/videos/{slug}.gif" if os.path.exists(local_path) else None,
        "remote_video": remote_url,
        "youtube_id": item["youtube_id"],
        "primary_muscle": item["primary_muscle"],
        "secondary_muscles": item["secondary_muscles"],
        "setup": item["setup"],
        "technique": item["technique"],
        "mistakes": item["mistakes"],
        "joint_safety": item["joint_safety"],
        "breathing": item["breathing"]
    }

