def main():
    print("=== 1. ЗАГРУЗКА АНИМИРОВАННЫХ GIF ДЛЯ НОВЫХ УПРАЖНЕНИЙ ===")
    os.makedirs("static/videos", exist_ok=True)
    base_url = "https://raw.githubusercontent.com/hasaneyldrm/exercises-dataset/main/"

    for item in NEW_EXERCISES:
        local_path = os.path.join("static", "videos", f"{item['slug']}.gif")
        if os.path.exists(local_path) and os.path.getsize(local_path) > 1000:
            print(f"  [OK] Уже существует: {local_path} ({os.path.getsize(local_path)} байт)")
            continue

        remote_url = base_url + item["dataset_gif"]
        print(f"  [>] Скачивание {item['name']} с {remote_url}...")
        try:
            req = urllib.request.Request(remote_url, headers={"User-Agent": "Mozilla/5.0"})
            with urllib.request.urlopen(req, timeout=20) as resp:
                data = resp.read()
                with open(local_path, "wb") as f:
                    f.write(data)
            print(f"  [✓] Успешно скачано: {local_path} ({len(data)} байт)")
        except Exception as e:
            print(f"  [!] Ошибка скачивания для {item['name']}: {e}")

    print("\n=== 2. ОБНОВЛЕНИЕ СПРАВОЧНИКА static/exercise_guides.json ===")
    guides_file = "static/exercise_guides.json"
    guides = {}
    if os.path.exists(guides_file):
        with open(guides_file, "r", encoding="utf-8") as f:
            guides = json.load(f)

    for item in NEW_EXERCISES:
        guides[item["name"]] = {
            "name": item["name"],
            "slug": item["slug"],
            "local_video": f"/static/videos/{item['slug']}.gif",
            "remote_video": base_url + item["dataset_gif"],
            "youtube_id": item["youtube_id"],
            "primary_muscle": item["primary_muscle"],
            "secondary_muscles": item["secondary_muscles"],
            "setup": item["setup"],
            "technique": item["technique"],
            "mistakes": item["mistakes"],
            "joint_safety": item["joint_safety"],
            "breathing": item["breathing"]
        }

    with open(guides_file, "w", encoding="utf-8") as f:
        json.dump(guides, f, ensure_ascii=False, indent=2)
    print(f"  [✓] Справочник обновлен. Всего упражнений с описанием и GIF: {len(guides)}")

    print("\n=== 3. ДОБАВЛЕНИЕ НОВЫХ УПРАЖНЕНИЙ В БАЗУ ДАННЫХ SQLite ===")
    conn = sqlite3.connect("workouts.db")
    cursor = conn.cursor()
    new_in_db = 0
    for item in NEW_EXERCISES:
        try:
            cursor.execute(
                "INSERT INTO exercises (name, category) VALUES (?, ?)",
                (item["name"], item["category"])
            )
            new_in_db += 1
            print(f"  ✓ Добавлено в exercises: {item['name']} ({item['category']})")
        except sqlite3.IntegrityError:
            print(f"  - Уже в базе: {item['name']}")
        except Exception as e:
            print(f"  ! Ошибка: {item['name']}: {e}")
    conn.commit()
    conn.close()
    print(f"  [✓] База данных обновлена. Добавлено новых записей: {new_in_db}")

if __name__ == "__main__":
    main()
